"""Best-effort kernel readiness; no alternative VPN engine is installed."""
import json
import os
from pathlib import Path
import subprocess
import sys

PRESETS={'wireguard_mtu':1360,'openvpn_tun_mtu':1360,'openvpn_mssfix':1320,'active':False}
MODULES=('tun','wireguard','af_key','ah4','esp4','ipcomp','xfrm4_tunnel','xfrm_user','nf_conntrack','tcp_bbr','sch_fq')


def settings():
    values={'net.ipv4.ip_forward':'1','net.ipv6.conf.all.forwarding':'1','net.ipv6.conf.default.forwarding':'1',
            'net.core.rmem_max':'16777216','net.core.wmem_max':'16777216','net.core.rmem_default':'1048576','net.core.wmem_default':'1048576',
            'net.core.optmem_max':'65536','net.core.netdev_max_backlog':'16384','net.ipv4.tcp_rmem':'4096 87380 16777216','net.ipv4.tcp_wmem':'4096 65536 16777216',
            'net.ipv4.tcp_mtu_probing':'1','net.ipv4.ip_no_pmtu_disc':'0','net.netfilter.nf_conntrack_max':'262144','fs.file-max':'2097152'}
    for scope in ('all','default'):
        values[f'net.ipv4.conf.{scope}.rp_filter']='2'
        for key in ('accept_redirects','send_redirects'):values[f'net.ipv4.conf.{scope}.{key}']='0'
        values[f'net.ipv6.conf.{scope}.accept_redirects']='0'
        # Router forwarding would otherwise disable host RA/default-route learning.
        values[f'net.ipv6.conf.{scope}.accept_ra']='2'
    return values


def command(args):
    try:
        p=subprocess.run(args,text=True,capture_output=True,timeout=15)
        return p.returncode==0,(p.stdout+p.stderr).strip()
    except (OSError,subprocess.TimeoutExpired) as e:return False,str(e)


def log(message):print('vpnaas-tuning: '+message,flush=True)


def configure():
    supported=[]
    for module in MODULES:
        ok,info=command(['modprobe',module])
        if ok:supported.append(module)
        log(f'module {module}: '+('available/loaded' if ok else 'UNAVAILABLE '+info))
    Path('/etc/modules-load.d/vpnaas.conf').write_text('\n'.join(supported)+'\n')
    values=settings()
    if 'sch_fq' in supported:values['net.core.default_qdisc']='fq'
    available=command(['sysctl','-n','net.ipv4.tcp_available_congestion_control'])[1].split()
    if 'bbr' in available:values['net.ipv4.tcp_congestion_control']='bbr'
    else:log('BBR unavailable; existing TCP congestion algorithm preserved')
    # Only allow explicit tuning overrides, not arbitrary sysctl injection.
    for key in list(values):
        override=os.environ.get('TUNE_'+key.upper().replace('.','_').replace('-','_'))
        if override:
            if not all(c.isdigit() or c==' ' for c in override):raise ValueError('Invalid numeric tuning override '+key)
            values[key]=override
    # Preserve RA on existing/late-attached interfaces, before forwarding flips.
    for item in Path('/proc/sys/net/ipv6/conf').iterdir():
        if item.name not in ('all','default','lo'):
            values[f'net.ipv6.conf.{item.name}.accept_ra']='2'
            command(['sysctl','-w',f'net.ipv6.conf.{item.name}.accept_ra=2'])
    applied={}
    # IPv4 forwarding transitions reset interface defaults: apply it first.
    ordered=sorted(values,key=lambda k:(k!='net.ipv4.ip_forward','forwarding' in k,k))
    for key in ordered:
        value=values[key]
        ok,info=command(['sysctl','-w',key+'='+value])
        log(info if ok else 'UNSUPPORTED/FAILED '+key+': '+info)
        if ok:applied[key]=value
    Path('/etc/sysctl.d/99-vpn-tuning.conf').write_text('# Generated by VPNaaS; supported settings only\n'+'\n'.join(k+'='+applied[k] for k in ordered if k in applied)+'\n')
    Path('/etc/vpnaas/future-vpn-presets.json').write_text(json.dumps(PRESETS,indent=2)+'\n')
    reconcile()


def reconcile():
    # Repeated feature reads avoid ioctl errors for unsupported/fixed offloads.
    from network import snapshot, public_interface
    dev=public_interface(snapshot())
    if not dev:return
    ok,features=command(['ethtool','-k',dev])
    if not ok:log(f'ethtool {dev}: '+features);return
    names={'gro':'generic-receive-offload','lro':'large-receive-offload','tx-udp_tnl-segmentation':'tx-udp_tnl-segmentation'}
    for feature,longname in names.items():
        line=next((s.strip() for s in features.splitlines() if s.strip().startswith(longname+':')),None)
        if not line or '[fixed]' in line:
            log(f'{dev} {feature}: unsupported/fixed ({line or "absent"})');continue
        if ': off' in line:continue
        success,info=command(['ethtool','-K',dev,feature,'off'])
        log(f'{dev} {feature}: '+('disabled' if success else 'FAILED '+info))
        if success:
            verified,current=command(['ethtool','-k',dev])
            if not verified or not any(s.strip().startswith(longname+': off') for s in current.splitlines()):
                log(f'{dev} {feature}: FAILED verification after change')
    # Do not touch MTU, addresses, routes, DHCP or QGA.


if __name__=='__main__':
    configure() if '--configure' in sys.argv else reconcile()
